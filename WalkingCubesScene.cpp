#include "WalkingCubesScene.h"
#include "SDFBuilder.h"

WalkingCubesScene::WalkingCubesScene()
{
    add(SDFBuilder()
        .combine<COMBAdd, SDFObject>()()
        .operate<OPCubeRollHeight>(1.0, 1.0, 0.5)
        .operate<OPTranslate>()
        .animate<ANLinearCycle3D>("translation", Vec3{ 0.5, 0.0, 0.5 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 0.5, 0.0, 1.5 })
        .operate<OPCubeRoller>(std::vector{ Vec3::Forward, Vec3::Right, Vec3::Backward, Vec3::Left }, 1.0, 0.5)
        .combine<COMBAdd, SDFBox>()().color(Color::Red)
        .stepBack(2)
        .combine<COMBAdd, SDFObject>()()
        .operate<OPTranslate>()
        .operate<OPTranslate>()
        .animate<ANLinearCycle3D>("translation", Vec3{ 0.5, 0.0, 0.5 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 0.5, 0.0, 1.5 })
        .operate<OPCubeRollHeight>(3.0, 1.0, 0.5)
        .operate<OPCubeRoller>(std::vector{ Vec3::Backward, Vec3::Left, Vec3::Forward, Vec3::Right }, 1.0, 0.5)
        .combine<COMBAdd, SDFBox>()().color(Color::Yellow)
        .stepBack(2)
        .combine<COMBAdd, SDFObject>()()
        .operate<OPRotate>()
        .operate<OPCubeRollHeight>(1.0, 1.0, 0.5)
        .operate<OPTranslate>()
        .animate<ANLinearCycle3D>("translation", Vec3{ 0.5, 0.0, 0.5 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 0.5, 0.0, 1.5 })
        .operate<OPCubeRoller>(std::vector{ Vec3::Forward, Vec3::Right, Vec3::Backward, Vec3::Left }, 1.0, 0.5)
        .combine<COMBAdd, SDFBox>()().color(Color::Blue)
        .stepBack(2)
        .combine<COMBAdd, SDFObject>()()
        .operate<OPTranslate>()
        .operate<OPRotate>()
        .operate<OPCubeRollHeight>(3.0, 1.0, 0.5)
        .operate<OPTranslate>()
        .animate<ANLinearCycle3D>("translation", Vec3{ 0.5, 0.0, 0.5 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 1.0, 1.0, 1.0 }, Vec3{ 0.5, 0.0, 1.5 })
        .operate<OPCubeRoller>(std::vector{ Vec3::Backward, Vec3::Left, Vec3::Forward, Vec3::Right }, 1.0, 0.5)
        .combine<COMBAdd, SDFBox>()().color(Color::Green)
        .stepBack(2)
        .addLightSource(Vec3{ 2.0, 6.0, -2.0 }, 50.0, Color::White)
    );
}
